#!/usr/bin/env bash
# Publish a generated trip site to the user's own GitHub Pages repository (no author domain needed).
# Usage: ./scripts/publish-gh-pages.sh /path/to/OUTPUT_SITE [trip-slug] [repo-name]
set -euo pipefail

SITE="${1:?Usage: $0 /path/to/OUTPUT_SITE [trip-slug] [repo-name]}"
if [[ ! -d "$SITE" || ! -f "$SITE/index.html" || ! -f "$SITE/data.js" ]]; then
  echo "Invalid site directory (missing index.html or data.js): $SITE" >&2
  exit 1
fi
SITE="$(cd "$SITE" && pwd)"

if ! command -v gh >/dev/null 2>&1; then
  echo "gh CLI is not installed. Install GitHub CLI or use publish-site.sh / bundle-single.sh." >&2
  exit 1
fi

if ! gh auth status >/dev/null 2>&1; then
  echo "gh CLI is not logged in. Run 'gh auth login' first, or use publish-site.sh / bundle-single.sh." >&2
  exit 1
fi

OWNER="$(gh api user -q .login)"
if [[ -z "$OWNER" ]]; then
  echo "Could not resolve GitHub username from gh CLI." >&2
  exit 1
fi

RAW_SLUG="${2:-$(basename "$SITE")}"
SLUG="$(printf '%s' "$RAW_SLUG" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9._-]+/-/g; s/^-+//; s/-+$//')"
if [[ -z "$SLUG" ]]; then
  SLUG="trip-$(date +%Y%m%d)"
fi
REPO="${3:-${TRAVEL_GUIDES_REPO:-travel-guides}}"

if ! gh repo view "$OWNER/$REPO" >/dev/null 2>&1; then
  echo "Creating public GitHub repository $OWNER/$REPO for GitHub Pages..."
  gh repo create "$OWNER/$REPO" --public --description "我的在线旅行路书集合（由 static-travel-guide 发布）" >/dev/null
fi

TMP="$(mktemp -d)"
cleanup() {
  if [[ -n "$TMP" && -d "$TMP" ]]; then rm -rf "$TMP"; fi
}
trap cleanup EXIT

REPO_DIR="$TMP/$REPO"
gh repo clone "$OWNER/$REPO" "$REPO_DIR" -- --depth 1 >/dev/null 2>&1 || {
  mkdir -p "$REPO_DIR"
  git -C "$REPO_DIR" init -b main >/dev/null
  git -C "$REPO_DIR" remote add origin "https://github.com/$OWNER/$REPO.git"
}

cd "$REPO_DIR"
if ! git rev-parse --verify HEAD >/dev/null 2>&1; then
  git checkout -B main >/dev/null 2>&1
  DEFAULT_BRANCH="main"
else
  DEFAULT_BRANCH="$(git symbolic-ref --short HEAD 2>/dev/null || echo main)"
fi

if [[ -z "$(git config user.name || true)" ]]; then
  git config user.name "$OWNER"
fi
if [[ -z "$(git config user.email || true)" ]]; then
  git config user.email "${OWNER}@users.noreply.github.com"
fi

# Copy generated site into /$SLUG/ without clobbering sibling trips
rm -rf "$REPO_DIR/$SLUG"
mkdir -p "$REPO_DIR/$SLUG"
rsync_copy() {
  python3 - "$SITE" "$REPO_DIR/$SLUG" <<'PY'
import shutil, sys
from pathlib import Path
src, dst = Path(sys.argv[1]), Path(sys.argv[2])
for item in src.iterdir():
    if item.name in (".git", ".DS_Store") or item.name.endswith("-offline.html"):
        continue
    target = dst / item.name
    if item.is_dir():
        shutil.copytree(item, target, ignore=shutil.ignore_patterns(".DS_Store"))
    else:
        shutil.copy2(item, target)
PY
}
rsync_copy

# Only create/update root index.html when missing or generated by this script
INDEX_MARKER="<!-- static-travel-guide-index -->"
if [[ ! -f "$REPO_DIR/index.html" ]] || grep -qF "$INDEX_MARKER" "$REPO_DIR/index.html"; then
  python3 - "$REPO_DIR" "$OWNER" "$REPO" "$INDEX_MARKER" <<'PY'
import html, json, re, sys
from pathlib import Path

repo_dir = Path(sys.argv[1])
owner, repo, marker = sys.argv[2], sys.argv[3], sys.argv[4]

cards = []
for sub in sorted(repo_dir.iterdir()):
    if not sub.is_dir() or sub.name.startswith("."):
        continue
    data_js = sub / "data.js"
    if not data_js.exists():
        continue
    text = data_js.read_text(encoding="utf-8", errors="ignore")
    m_title = re.search(r'\btitle\s*:\s*"([^"]+)"', text)
    m_start = re.search(r'\bstart\s*:\s*"([^"]*)"', text)
    m_end = re.search(r'\bend\s*:\s*"([^"]*)"', text)
    title = m_title.group(1) if m_title else sub.name
    dates = ""
    if m_start and m_start.group(1):
        dates = m_start.group(1)
        if m_end and m_end.group(1) and m_end.group(1) != dates:
            dates = f"{dates} – {m_end.group(1)}"
    cards.append((sub.name, title, dates))

items_html = "\n".join(
    f'      <a class="card" href="./{html.escape(slug)}/"><b>{html.escape(title)}</b>'
    f'<span>{html.escape(dates or "在线路书")}</span></a>'
    for slug, title, dates in cards
)

page = f"""<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>我的行程库</title>
  <style>
    body {{ margin: 0; font-family: -apple-system, BlinkMacSystemFont, "PingFang SC", sans-serif; background: #f7f5f0; color: #17231f; }}
    main {{ max-width: 720px; margin: 0 auto; padding: 36px 20px 60px; }}
    h1 {{ margin: 0 0 8px; font-size: 28px; }}
    p {{ margin: 0 0 24px; color: #66736e; font-size: 14px; }}
    .grid {{ display: grid; gap: 12px; }}
    .card {{ display: flex; justify-content: space-between; align-items: center; gap: 12px; padding: 16px 18px; border-radius: 14px; background: #fff; border: 1px solid #eae6dd; text-decoration: none; color: inherit; }}
    .card:hover {{ border-color: #0d5c54; }}
    .card b {{ font-size: 16px; }}
    .card span {{ color: #66736e; font-size: 13px; white-space: nowrap; }}
  </style>
</head>
<body>
  {marker}
  <main>
    <h1>我的行程库</h1>
    <p>由 static-travel-guide 发布到 {html.escape(owner)}.github.io/{html.escape(repo)}</p>
    <div class="grid">
{items_html}
    </div>
  </main>
</body>
</html>
"""
(repo_dir / "index.html").write_text(page, encoding="utf-8")
PY
fi

git add -A
if [[ -n "$(git status --porcelain)" ]]; then
  git commit -m "chore: publish trip $SLUG" >/dev/null
  git push -u origin "$DEFAULT_BRANCH" >/dev/null
fi

# Ensure GitHub Pages is enabled
if ! gh api "repos/$OWNER/$REPO/pages" >/dev/null 2>&1; then
  gh api "repos/$OWNER/$REPO/pages" -X POST \
    -f build_type="legacy" \
    -f "source[branch]=$DEFAULT_BRANCH" \
    -f "source[path]=/" >/dev/null 2>&1 || true
fi

PUBLIC_URL="https://${OWNER}.github.io/${REPO}/${SLUG}/"
echo "Published to your own GitHub Pages:"
echo "Public: $PUBLIC_URL"
echo "Repo: https://github.com/${OWNER}/${REPO}"
echo "Note: First-time GitHub Pages builds can take ~15-60 seconds to go live."
